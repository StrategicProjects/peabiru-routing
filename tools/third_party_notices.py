#!/usr/bin/env python3
"""Licence notices of the Rust crates compiled into peabiru's binaries.

The Python extension module, the R package's shared library and the
command-line tool link code from other crates (pyo3, extendr, miniz_oxide,
...). Their licences ask for their copyright notices and licence texts to
travel with the binaries, so this script writes, for each binary, a file
with every crate linked into it: name, version, licence expression,
authors, repository and the licence files the crate itself ships. It also
writes the R package's inst/AUTHORS, which lists every crate the package's
build uses (what `cargo vendor` will put in the CRAN tarball), and copies
LICENSE-MIT and LICENSE-THIRD-PARTY from the root to the packages.

The files are generated by maintainers and committed; nothing here runs at
build time. Run it after any change to a Cargo.lock:

    python3 tools/third_party_notices.py          # write the files
    python3 tools/third_party_notices.py --check  # fail if any is stale

It needs only Python 3.8+ and cargo; `cargo metadata --locked` reads the
lockfiles as they are and fetches the crates' sources if they are missing.

Which crates count as linked: starting from the package, follow its normal
dependencies (not build or dev dependencies) on any target platform. A
procedural-macro crate is included, because the code it expands to is
compiled into the binary, but its own dependencies (syn, quote, ...) run
only inside the compiler and are not followed. The crates of this
repository (peabiru-*) are covered by LICENSE-MIT and LICENSE-THIRD-PARTY
and are left out.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# (output file, manifest, package, what the binary is)
NOTICES = [
    (
        "python/LICENSE-RUST-CRATES",
        "Cargo.toml",
        "peabiru-python",
        "the Python package's extension module (peabiru/_peabiru)",
    ),
    (
        "r/inst/LICENSE-RUST-CRATES",
        "r/src/rust/Cargo.toml",
        "peabiru",
        "the R package's shared library (libs/peabiru)",
    ),
    (
        "crates/peabiru-cli/LICENSE-RUST-CRATES",
        "Cargo.toml",
        "peabiru-cli",
        "the peabiru command-line tool",
    ),
]

# (output file, manifest, package)
AUTHORS = ("r/inst/AUTHORS", "r/src/rust/Cargo.toml", "peabiru")

# Root licence files and the packages that carry identical copies.
COPIES = {
    "LICENSE-MIT": ["crates/peabiru-core", "crates/peabiru-cli", "python"],
    "LICENSE-THIRD-PARTY": [
        "crates/peabiru-core",
        "crates/peabiru-cli",
        "python",
        "r/inst",
    ],
}

# Crates whose published package ships no licence file. The text below was
# taken from the crate's repository at the tag of the version named; when
# the version in a lockfile changes, check the repository again and update
# the entry (the script refuses to run with a version it has no entry for).
